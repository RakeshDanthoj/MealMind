export function getDishById(dishId: string): DishCatalogItem | undefined {
  return MOCK_DISH_CATALOG.find(dish => dish.dish_id === dishId);
}

export function getDishesBySlot(slot: MealSlot): DishCatalogItem[] {
  return MOCK_DISH_CATALOG.filter(dish => dish.meal_slots.includes(slot) && dish.active);
}

export function getDishesByCuisine(cuisines: CuisineType[]): DishCatalogItem[] {
  return MOCK_DISH_CATALOG.filter(
    dish => dish.cuisines.some(c => cuisines.includes(c)) && dish.active
  );
}

export function getDishesByComplexity(maxComplexity: CookingSkill): DishCatalogItem[] {
  const complexityOrder: CookingSkill[] = ['beginner', 'comfortable', 'advanced'];
  const maxIndex = complexityOrder.indexOf(maxComplexity);
  
  return MOCK_DISH_CATALOG.filter(
    dish => complexityOrder.indexOf(dish.prep_complexity) <= maxIndex && dish.active
  );
}

export function filterDishesForUser(
  slot: MealSlot,
  cuisines: CuisineType[],
  allergens: string[],
  cookingSkill: CookingSkill,
  avoidDishIds: string[] = []
): DishCatalogItem[] {
  const complexityOrder: CookingSkill[] = ['beginner', 'comfortable', 'advanced'];
  const maxComplexityIndex = complexityOrder.indexOf(cookingSkill);

  return MOCK_DISH_CATALOG.filter(dish => {
    if (!dish.active) return false;
    if (!dish.meal_slots.includes(slot)) return false;
    if (!dish.cuisines.some(c => cuisines.includes(c))) return false;
    if (dish.allergens.some(a => allergens.includes(a.toLowerCase()))) return false;
    if (complexityOrder.indexOf(dish.prep_complexity) > maxComplexityIndex) return false;
    if (avoidDishIds.includes(dish.dish_id)) return false;
    return true;
  });
}
